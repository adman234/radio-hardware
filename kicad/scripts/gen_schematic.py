"""Writes jar-radio.kicad_sch and lib/jar-radio.kicad_sym from circuit.py."""
import os, sys
from schlib import Schematic, G
import circuit

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.join(HERE, '..')

BLOCKS = {  # block: (title, x0, y0, x1, y1, columns)
    'tuner': ('FM TUNER - Si4825, station set by R2/R3 (KOPN 89.5 MHz), band FM3 by R5/R6', 15.24, 20.32, 215.9, 137.16, 9),
    'ant': ('ANTENNA - wire soldered into J3 (2 zip-tie holes) or telescopic whip on ANT1; AN738 whip network', 15.24, 147.32, 109.22, 205.74, 4),
    'audio': ('AUDIO - volume pot RV1, NS8002 class AB BTL, Av = 2*R8/R7 = 20', 223.52, 20.32, 403.86, 137.16, 7),
    'power': ('POWER - USB-C in, TP4056 charger, AN1149 load sharing, slide switch SW1, 3.3 V LDO', 119.38, 147.32, 403.86, 279.4, 11),
    'test': ('TEST PADS', 15.24, 215.9, 109.22, 279.4, 6),
}


def main():
    s = Schematic('KOPN 89.5 Jar Radio')
    for d in circuit.SYMS:
        s.add_def(d)
    for b, (title, x0, y0, x1, y1, cols) in BLOCKS.items():
        s.box(x0, y0, x1, y1)
        s.text(title, x0 + 1.27, y0 + 3.81, 1.524, bold=True)
        parts = [p for p in circuit.P if p['block'] == b]
        big = [p for p in parts if not circuit.SYM_BY_NAME[p['sym']].two_pin and len(circuit.SYM_BY_NAME[p['sym']].pins) > 3]
        small = [p for p in parts if p not in big]
        x = x0 + 25.4
        for p in big:
            d = circuit.SYM_BY_NAME[p['sym']]
            px = x + d.w / 2 + 7.62
            py = y0 + 12.7 + d.h / 2
            py = round(py / 2.54) * 2.54; px = round(px / 2.54) * 2.54
            place(s, p, px, py)
            x = px + d.w / 2 + 25.4
        cx, cy = x if big else x0 + 12.7, y0 + 17.78
        row_start = cx
        colw = 20.32
        for p in small:
            d = circuit.SYM_BY_NAME[p['sym']]
            # 3-pin parts have side stubs + labels: give them room on both sides
            pad = 0 if d.two_pin else max(abs(q[2]) for q in d.pins) + 7.62
            cx += pad
            if cx + 10 > x1:
                cx = x0 + 12.7 if big and cy + 30 > y0 + 12.7 + max(circuit.SYM_BY_NAME[q['sym']].h for q in big) else row_start
                cy += 25.4
            px = round(cx / 2.54) * 2.54; py = round((cy + 5) / 2.54) * 2.54
            place(s, p, px, py)
            cx += colw + pad
    s.text('Values in the LCSC/MPN fields drive the JLC BOM. DNP = footprint only. Hand = soldered by hand, not by JLC.',
           15.24, 289.56, 1.27)
    s.write(os.path.join(PROJ, 'jar-radio.kicad_sch'), rev='A', date='2026-10-20',
            comments=('KOPN 89.5 FM single-station jar-lid radio', 'Fork of The Public Radio (Wright & Dunham)',
                      'Hardware licence: CERN-OHL-S-2.0', 'Generated by kicad/scripts/gen_schematic.py'))
    s.write_lib(os.path.join(PROJ, 'lib', 'jar-radio.kicad_sym'))
    return s


def place(s, p, x, y):
    fields = {}
    if p.get('dnp'):
        fields['Note'] = 'DNP'
    if p.get('hand'):
        fields['Assembly'] = 'Hand'
    s.part(p['ref'], p['sym'], p['value'], x, y, p['nets'], footprint=p['footprint'],
           lcsc=p['lcsc'], mpn=p['mpn'], fields=fields, dnp=p.get('dnp', False), nc=p.get('nc', ()))


if __name__ == '__main__':
    main()
